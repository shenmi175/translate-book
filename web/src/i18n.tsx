const I18nContext = createContext<I18nContextValue | null>(null);

function interpolate(template: string, vars?: Record<string, string | number | null | undefined>) {
  if (!vars) {
    return template;
  }

  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => String(vars[key] ?? ''));
}

function resolveInitialLocale(): Locale {
  if (typeof window !== 'undefined') {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === 'zh-CN' || stored === 'en') {
      return stored;
    }

    if (window.navigator.language.toLowerCase().startsWith('zh')) {
      return 'zh-CN';
    }
  }

  return 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(resolveInitialLocale);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => {
    const currentMessages = messages[locale];
    const fallbackMessages = messages.en;

    const t = (key: string, vars?: Record<string, string | number | null | undefined>) => {
      const template = currentMessages[key] ?? fallbackMessages[key] ?? key;
      return interpolate(template, vars);
    };

    return {
      locale,
      dateLocale: locale === 'zh-CN' ? 'zh-CN' : 'en-US',
      setLocale,
      t,
      tTaskStage: (stage: string) => t(`task.stage.${stage}`),
      tBlockStatus: (status: string) => t(`block.status.${status}`)
    };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within I18nProvider.');
  }
  return context;
}
